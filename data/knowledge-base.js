function makeSummary(text) {
    const clean = String(text).replace(/\s+/g, ' ').trim();
    const cut = clean.slice(0, 130);
    return clean.length > 130 ? cut.slice(0, cut.lastIndexOf(' ')) + '…' : clean;
}

function makeTags(title, categoryTitle) {
    const stop = new Set(['في','من','على','عن','إلى','الى','the','and','for','a','of']);
    return [...new Set(
        (title + ' ' + categoryTitle)
            .replace(/[()\/،,.:–—-]/g, ' ')
            .split(/\s+/)
            .map(w => w.trim())
            .filter(w => w.length > 2 && !stop.has(w.toLowerCase()))
    )].slice(0, 8);
}

